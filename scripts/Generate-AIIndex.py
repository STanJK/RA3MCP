#!/usr/bin/env python3
"""Generate the compact RA3 SkirmishAI AssetId name index.

The source directory is the official Electronic Arts CnC_Modding_Support
checkout.  Only identifiers and small display-name fields are emitted; the
game XML itself is not copied into RA3MCP.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET


ASSET_NS = "{uri:ea.com:eala:asset}"


def asset_hash(text: str, fold_case: bool = True) -> int:
    data = (text.lower() if fold_case else text).encode("ascii")
    value = len(data)
    at = 0
    for _ in range(len(data) // 4):
        part = (data[at] | data[at + 1] << 8) + value
        part &= 0xFFFFFFFF
        mixed = ((((part * 32) & 0xFFFFFFFF) ^ (data[at + 2] | data[at + 3] << 8)) << 11) & 0xFFFFFFFF
        mixed ^= part
        value = ((mixed >> 11) + mixed) & 0xFFFFFFFF
        at += 4

    remaining = len(data) & 3
    if remaining == 1:
        part = (value + data[at]) & 0xFFFFFFFF
        mixed = ((part << 10) & 0xFFFFFFFF) ^ part
        value = ((mixed >> 1) + mixed) & 0xFFFFFFFF
    elif remaining == 2:
        part = (value + (data[at] | data[at + 1] << 8)) & 0xFFFFFFFF
        mixed = ((part << 11) & 0xFFFFFFFF) ^ part
        value = ((mixed >> 17) + mixed) & 0xFFFFFFFF
    elif remaining == 3:
        part = (value + (data[at] | data[at + 1] << 8)) & 0xFFFFFFFF
        mixed = ((((part ^ (4 * data[at + 2])) << 16) & 0xFFFFFFFF) ^ part) & 0xFFFFFFFF
        value = ((mixed >> 11) + mixed) & 0xFFFFFFFF

    value = ((((value * 8) & 0xFFFFFFFF) ^ value) >> 5) + (((value * 8) & 0xFFFFFFFF) ^ value)
    value &= 0xFFFFFFFF
    value = ((((value * 4) & 0xFFFFFFFF) ^ value) >> 15) + (((value * 4) & 0xFFFFFFFF) ^ value)
    value &= 0xFFFFFFFF
    return (((value << 10) & 0xFFFFFFFF) ^ value) & 0xFFFFFFFF


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def collect(xml_root: Path, tag: str) -> dict[str, ET.Element]:
    values: dict[str, ET.Element] = {}
    for path in sorted(xml_root.rglob("*.xml")):
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError as error:
            raise SystemExit(f"failed to parse {path}: {error}") from error
        for element in root.iter(ASSET_NS + tag):
            identifier = element.get("id")
            if identifier:
                values[identifier] = element
    return values


def plain_table(name: str, values: dict[str, ET.Element]) -> list[str]:
    rows = sorted((asset_hash(identifier), identifier) for identifier in values)
    lines = [f"pub const {name}: &[AssetName] = &["]
    lines.extend(f"    AssetName {{ instance_id: 0x{value:08X}, name: {rust_string(identifier)} }}," for value, identifier in rows)
    lines.append("];\n")
    return lines


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source_root", type=Path, help="path to 'Red Alert 3/Xml/SkirmishAI'")
    parser.add_argument("output", type=Path, help="controller/src/ai_index.rs")
    args = parser.parse_args()
    xml_root = args.source_root.resolve()
    if not xml_root.is_dir():
        raise SystemExit(f"not a directory: {xml_root}")

    personalities = collect(xml_root / "Personalities", "AIPersonalityDefinition")
    strategic = collect(xml_root / "States", "AIStrategicStateDefinition")
    budgets = collect(xml_root / "States", "AIBudgetStateDefinition")
    builds = collect(xml_root / "States", "AIBuildStateDefinition")

    lines = [
        "// @generated by scripts/Generate-AIIndex.py; do not edit by hand.",
        "// Source: Electronic Arts CnC_Modding_Support / Red Alert 3 / Xml / SkirmishAI.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct AssetName {",
        "    pub instance_id: u32,",
        "    pub name: &'static str,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct PersonalityName {",
        "    pub instance_id: u32,",
        "    pub name: &'static str,",
        "    pub personality_type: &'static str,",
        "    pub ui_name: &'static str,",
        "}",
        "",
        "pub const PERSONALITIES: &[PersonalityName] = &[",
    ]
    personality_rows = []
    for identifier, element in personalities.items():
        personality_rows.append((asset_hash(identifier), identifier, element.get("PersonalityType", ""), element.get("PersonalityUIName", "")))
    for value, identifier, personality_type, ui_name in sorted(personality_rows):
        lines.append(
            "    PersonalityName { instance_id: "
            f"0x{value:08X}, name: {rust_string(identifier)}, personality_type: {rust_string(personality_type)}, "
            f"ui_name: {rust_string(ui_name)} }},"
        )
    lines.append("];\n")
    lines.extend(plain_table("STRATEGIC_STATES", strategic))
    lines.extend(plain_table("BUDGET_STATES", budgets))
    lines.extend(plain_table("BUILD_STATES", builds))
    lines.extend([
        "fn find(table: &'static [AssetName], instance_id: u32) -> Option<&'static AssetName> {",
        "    table.binary_search_by_key(&instance_id, |entry| entry.instance_id).ok().map(|index| &table[index])",
        "}",
        "",
        "pub fn personality(instance_id: u32) -> Option<&'static PersonalityName> {",
        "    PERSONALITIES.binary_search_by_key(&instance_id, |entry| entry.instance_id).ok().map(|index| &PERSONALITIES[index])",
        "}",
        "pub fn strategic_state(instance_id: u32) -> Option<&'static AssetName> { find(STRATEGIC_STATES, instance_id) }",
        "pub fn budget_state(instance_id: u32) -> Option<&'static AssetName> { find(BUDGET_STATES, instance_id) }",
        "pub fn build_state(instance_id: u32) -> Option<&'static AssetName> { find(BUILD_STATES, instance_id) }",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "    #[test]",
        "    fn generated_tables_are_sorted_and_known_assets_resolve() {",
        "        for table in [STRATEGIC_STATES, BUDGET_STATES, BUILD_STATES] {",
        "            assert!(table.windows(2).all(|pair| pair[0].instance_id < pair[1].instance_id));",
        "        }",
        "        assert_eq!(strategic_state(0x7C55_E8D8).map(|entry| entry.name), Some(\"BalancedDefense\"));",
        "        assert_eq!(personality(0x7B9D_A0E6).map(|entry| entry.name), Some(\"1SovietBalanced\"));",
        "    }",
        "}",
        "",
    ])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
